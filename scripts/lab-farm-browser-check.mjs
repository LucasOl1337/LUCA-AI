// Run against the isolated server from scripts/sompo-demo.mjs, never production.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const base = new URL(process.env.LAB_TEST_URL || 'http://127.0.0.1:4245');
assert.ok(['127.0.0.1', 'localhost'].includes(base.hostname));
const output = 'docs/audit/farm';
fs.mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => {
    const url = new URL(route.request().url());
    return ['127.0.0.1', 'localhost'].includes(url.hostname) || ['data:', 'blob:'].includes(url.protocol) ? route.continue() : route.abort();
  });
  await page.goto(new URL('/sompo', base).href);
  const registration = await page.request.post(new URL('/api/auth/register', base).href, { data: { name: 'Farm browser fixture', email: `farm-${Date.now()}@example.test`, password: 'Farm-local-test-12345' } });
  assert.equal(registration.status(), 201);
  await page.reload();
  await page.locator('[data-lab-scene][data-satellite="ready"][data-site="frying-pan-farm-fairfax-v1"]').waitFor();
  await page.locator('[data-lab-scene][data-terrain="ready"]').waitFor();
  assert.equal(await page.locator('[data-lab-canvas] canvas').count(), 1);
  assert.ok(await page.getByRole('button', { name: 'Acompanhar', exact: true }).isDisabled());
  assert.equal(await page.locator('#lab-case-panel').isVisible(), false);
  assert.equal(await page.locator('.lab-scene-legend').isVisible(), false);
  await page.getByRole('button', { name: 'Ver caminhão em movimento', exact: true }).click();
  await page.waitForFunction(() => Number(document.querySelector('[data-lab-canvas]')?.dataset.sampleIndex) > 5);
  await page.getByRole('button', { name: 'Pausar reprodução', exact: true }).click();
  assert.equal(await page.locator('[data-lab-scene]').getAttribute('data-camera'), 'follow');
  assert.match(await page.locator('.lab-demo-badge').innerText(), /SINTÉTICO/);
  await page.screenshot({ path: `${output}/06-caminhao-proximo.png`, fullPage: true });
  await page.getByRole('button', { name: 'Carregar caso', exact: true }).click();
  await page.getByText('Área do laboratório', { exact: true }).click();
  await page.getByRole('button', { name: 'Explorar área sem telemetria', exact: true }).click();
  await page.getByRole('button', { name: 'Camadas e fontes', exact: true }).click();
  assert.match(await page.locator('.lab-scene-legend').innerText(), /Área operacional não fornecida/);
  await page.screenshot({ path: `${output}/01-area-real.png`, fullPage: true });
  await page.getByRole('button', { name: 'Livre', exact: true }).click();
  await page.locator('[data-lab-scene][data-camera="free"]').waitFor();
  await page.screenshot({ path: `${output}/05-relevo-lidar.png`, fullPage: true });
  await page.getByRole('button', { name: 'Relevo LiDAR ativado', exact: true }).click();
  await page.locator('[data-lab-scene][data-terrain="flat"]').waitFor();
  await page.getByRole('button', { name: 'Relevo LiDAR desativado', exact: true }).click();
  await page.locator('[data-lab-scene][data-terrain="ready"]').waitFor();
  await page.getByRole('button', { name: 'Superior', exact: true }).click();
  const dataset = { samples: [0, 1, 2, 3].map(i => ({
    tractorId: 'ESP32-BROWSER-FIXTURE', sourceKind: 'firebase', observedAt: `2026-09-09T12:00:0${i}.000Z`,
    temperatura: 28 + i, distancia: 50 - i * 10, riscoColisao: i > 1, riscoInclinacao: false,
  })) };
  const savedResponse = page.waitForResponse(response => response.url().endsWith('/api/lab/cases') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Carregar caso', exact: true }).click();
  await page.getByLabel('Carregar CSV ou JSON do gêmeo digital', { exact: true }).setInputFiles({ name: 'historico-fixture.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(dataset)) });
  const saved = await (await savedResponse).json();
  assert.equal(saved.case.metadata.site.id, 'frying-pan-farm-fairfax-v1');
  assert.equal(saved.case.metadata.synthetic, false);
  assert.equal(saved.case.map.features.length, 5);
  await page.locator('[data-lab-canvas][data-gps="missing"][data-position="unavailable"]').waitFor();
  await page.getByRole('button', { name: 'Sensores ESP32', exact: true }).click();
  await page.locator('[data-lab-esp32]').waitFor();
  await page.getByRole('button', { name: 'Reproduzir operação', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[data-lab-clock]')?.textContent?.startsWith('00:03.0'));
  await page.getByRole('button', { name: 'Mapa da área', exact: true }).click();
  await page.locator('[data-lab-canvas][data-sample-index="3"][data-position="unavailable"]').waitFor();
  await page.screenshot({ path: `${output}/02-esp32-sem-gnss.png`, fullPage: true });
  await page.reload();
  await page.locator('[data-lab-scene][data-satellite="ready"][data-site="frying-pan-farm-fairfax-v1"]').waitFor();
  await page.locator('[data-lab-canvas][data-position="unavailable"]').waitFor();
  const restored = await (await page.request.get(new URL(`/api/lab/cases/${saved.case.id}`, base).href)).json();
  assert.deepEqual(restored.case.map, saved.case.map);
  assert.deepEqual(restored.case.metadata.satellite, saved.case.metadata.satellite);
  assert.deepEqual(restored.case.metadata.terrain, saved.case.metadata.terrain);
  const terrainPattern = '**/datasets/frying-pan-farm/terrain-2022-5m.json';
  await page.route(terrainPattern, route => route.fulfill({ contentType: 'application/json', body: '{}' }));
  await page.reload();
  await page.locator('[data-lab-scene][data-terrain="error"]').waitFor();
  await page.getByRole('button', { name: 'Camadas e fontes', exact: true }).click();
  assert.match(await page.locator('.lab-scene-terrain').innerText(), /Checksum.*Superfície plana mantida/);
  await page.unroute(terrainPattern);
  await page.reload();
  await page.locator('[data-lab-scene][data-terrain="ready"]').waitFor();
  await page.getByRole('button', { name: 'Abrir casos salvos', exact: true }).click();
  await page.getByText('Área do laboratório', { exact: true }).click();
  await page.getByLabel('Carregar manifesto e GeoJSON da área', { exact: true }).setInputFiles(['public/datasets/frying-pan-farm/manifest.json', 'public/datasets/frying-pan-farm/mapa.geojson']);
  await page.waitForFunction(() => document.querySelector('select[aria-label="Área para associar"]')?.value === 'custom');
  await page.getByRole('button', { name: 'Explorar área sem telemetria', exact: true }).click();
  await page.locator('[data-lab-scene][data-satellite="ready"]').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${output}/03-mobile.png`, fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Carregar caso', exact: true }).click();
  await page.locator('[data-lab-example="water"]').click();
  await page.locator('[data-lab-canvas][data-gps="available"]').waitFor();
  assert.equal(await page.locator('[data-lab-scene]').getAttribute('data-site'), null);
  assert.equal(await page.locator('[data-lab-scene]').getAttribute('data-terrain'), 'flat');
  await page.getByRole('button', { name: 'Camadas e fontes', exact: true }).click();
  assert.match(await page.locator('.lab-scene-legend').innerText(), /Percurso sintético/);
  assert.ok(await page.locator('[data-lab-event]').count() > 0);
  await page.screenshot({ path: `${output}/04-exemplo-preservado.png`, fullPage: true });
  assert.deepEqual(errors, []);
  const report = { passed: ['scene-first-collapsed-panels', 'synthetic-truck-follow-replay', 'real-area-preview', 'aerial-loaded-locally', 'lidar-relief-and-flat-toggle', 'terrain-checksum-failure-fallback', 'camera-free-top', 'ESP32-JSON-import', 'no-fabricated-GNSS', 'sensor-and-map-replay', 'save-reload-with-terrain', 'custom-area-upload', 'mobile-no-overflow', 'original-water-example-flat'], browserErrors: errors };
  fs.writeFileSync(`${output}/browser-check.json`, JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify(report));
} finally { await browser.close(); }
