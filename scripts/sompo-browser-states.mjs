import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { normalizeSompoTelemetry } from '../shared/sompo-telemetry.js';
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
// Browser fixture only. No Firebase, hardware or runtime physical feed is modified.
let socket;
let resolveSocket;
const socketReady = new Promise(resolve => { resolveSocket = resolve; });
await page.routeWebSocket('**/ws', ws => { socket = ws; resolveSocket(); });
await page.goto('http://127.0.0.1:4243/sompo');
const registered = await page.request.post('http://127.0.0.1:4243/api/auth/register', { data: { name: 'Estados locais', email: `states-${Date.now()}@example.test`, password: 'Demo-local-12345' } });
assert.equal(registered.status(), 201);
await page.reload();
await page.getByRole('heading', { name: 'Risco em campo', exact: true }).waitFor();
await socketReady;
const reading = normalizeSompoTelemetry({ temperatura: 38, umidade: 90, distancia: 100, riscoColisao: false, riscoInclinacao: false });
reading.freshness = 'fresh'; reading.connection.state = 'live';
socket.send(JSON.stringify({ kind: 'sompo.telemetry', telemetry: reading }));
await page.getByRole('combobox', { name: /^Tipo de operação/ }).selectOption('proximidade de agua');
await page.getByRole('combobox', { name: /^Condição da região/ }).selectOption('alagada');
await page.getByLabel('Incidentes no histórico disponível', { exact: true }).fill('5');
assert.match(await page.locator('[data-sompo-score]').innerText(), /91/);
await page.route('**/api/sompo/risk', route => route.request().method() === 'POST' ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"Fixture indisponível"}' }) : route.continue());
await page.getByRole('button', { name: 'Registrar avaliação', exact: true }).click();
await page.getByText('Falha ao registrar. Confira a conexão e os dados e tente novamente.', { exact: true }).waitFor();
socket.send(JSON.stringify({ kind: 'sompo.telemetry', telemetry: { ...reading, changedAt: new Date(Date.now() - 20000).toISOString() } }));
await page.getByText('Última leitura · condição atual desconhecida', { exact: true }).waitFor();
assert.equal(await page.getByRole('button', { name: 'Registrar avaliação', exact: true }).isDisabled(), true);
await page.locator('[data-sompo-telemetry]').scrollIntoViewIfNeeded();
await page.screenshot({ path: 'docs/audit/ui-stale.png' });
const incomplete = normalizeSompoTelemetry({ temperatura: 27, distancia: null });
socket.send(JSON.stringify({ kind: 'sompo.telemetry', telemetry: incomplete }));
await page.getByText('Condição não confirmada', { exact: true }).waitFor();
assert.ok((await page.getByText('Não informado', { exact: true }).count()) >= 2);
await page.screenshot({ path: 'docs/audit/ui-incomplete.png' });
assert.deepEqual(errors, []);
console.log(JSON.stringify({ passed: ['high-score-91', 'save-error', 'stale-score-disabled', 'unknown-flags', 'no-js-errors'] }));
await browser.close();
