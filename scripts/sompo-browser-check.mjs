import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await page.route('**/*', route => { const u = new URL(route.request().url()); return ['127.0.0.1','localhost'].includes(u.hostname) || ['data:','blob:'].includes(u.protocol) ? route.continue() : route.abort(); });
await page.goto('http://127.0.0.1:4243/sompo');
const reg = await page.request.post('http://127.0.0.1:4243/api/auth/register', { data: { name: 'Demo Sompo', email: `demo-${Date.now()}@example.test`, password: 'Demo-local-12345' } });
assert.equal(reg.status(), 201);
await page.reload();
await page.getByRole('heading', { name: 'Risco em campo', exact: true }).waitFor();
await page.getByText('Não foi possível ler o trator', { exact: true }).waitFor();
await page.screenshot({ path: 'docs/audit/ui-no-data.png' });
await page.getByRole('button', { name: 'Simulador 3D Dados sintéticos · sem equipamento' }).click();
await page.getByRole('combobox', { name: /^Tipo de operação/ }).selectOption('campo');
await page.getByRole('combobox', { name: /^Condição da região/ }).selectOption('rural');
await page.getByLabel('Incidentes no histórico disponível', { exact: true }).fill('0');
await page.getByRole('button', { name: 'Registrar avaliação', exact: true }).click();
await page.getByText('Avaliação registrada com as entradas e a versão da regra.', { exact: true }).waitFor();
assert.match(await page.locator('[data-sompo-score]').innerText(), /12/);
await page.locator('[data-sompo-score]').scrollIntoViewIfNeeded();
await page.screenshot({ path: 'docs/audit/ui-score-desktop.png' });
await page.reload();
await page.getByText('Avaliações registradas · 1', { exact: true }).waitFor();
await page.getByRole('button', { name: 'Obstáculo frontal', exact: true }).click();
await page.getByText('Alerta simulado · verifique o cenário', { exact: true }).waitFor();
await page.locator('[data-sompo-telemetry]').scrollIntoViewIfNeeded();
await page.screenshot({ path: 'docs/audit/ui-alert.png' });
await page.getByRole('combobox', { name: /^Tipo de operação/ }).selectOption('proximidade de agua');
await page.getByRole('combobox', { name: /^Condição da região/ }).selectOption('alagada');
await page.getByLabel('Incidentes no histórico disponível', { exact: true }).fill('5');
const episodeCreated = page.waitForResponse(r => r.url().endsWith('/api/sompo/telemetry/episode') && r.request().method() === 'POST');
await page.getByRole('button', { name: 'Simular colisão', exact: true }).click();
const created = await (await episodeCreated).json();
await page.locator('[data-sompo-collision-done]').waitFor({ timeout: 60000 });
const episode = await (await page.request.get(`http://127.0.0.1:4243/api/sompo/telemetry/episode/${created.episode.publicId}`)).json();
assert.equal(episode.episode.status, 'complete');
assert.equal(episode.samples.length, 45);
assert.deepEqual(episode.samples.map(s => s.deviceTimestamp), Array.from({ length: 45 }, (_, i) => i * 500));
assert.equal(episode.frames.length, 5);
assert.ok(episode.frames[0].offsetMs < 500);
const history = await (await page.request.get('http://127.0.0.1:4243/api/sompo/telemetry/history?fonte=simulacao&trator=SIM-001')).json();
assert.ok(history.samples.length > 10);
await page.screenshot({ path: 'docs/audit/ui-episode.png' });
await page.setViewportSize({ width: 390, height: 844 });
await page.locator('[data-sompo-score]').scrollIntoViewIfNeeded();
await page.screenshot({ path: 'docs/audit/ui-score-mobile.png' });
await page.reload();
await page.getByText('Episódio selecionado:', { exact: false }).waitFor();
await page.getByRole('button', { name: 'Analisar colisão na bancada', exact: true }).waitFor();
const overflowing = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
assert.equal(overflowing, false);
await page.evaluate(() => {
  const original = Storage.prototype.setItem;
  Storage.prototype.setItem = function(key, value) {
    if (key === 'luca.lucaAi.sompoLaunch') window.__sompoLaunchEvidence = JSON.parse(value);
    return original.call(this, key, value);
  };
});
await page.getByRole('button', { name: 'Analisar colisão na bancada', exact: true }).click();
await page.waitForURL('**/luca-ai**');
const launch = await page.evaluate(() => window.__sompoLaunchEvidence);
assert.equal(launch.attachments.length, 4);
assert.match(launch.mission, /Cobertura pendente/);
assert.match(launch.mission, /não anexado|não foi anexado|fora do orçamento|omitid/i);
console.log(JSON.stringify({ benchAttachments: launch.attachments.length, episodeFrames: episode.frames.length, episodeSamples: episode.samples.length, passed: ['no-data', 'normal-score-12', 'save-reload', 'critical-alert', 'collision-episode', 'mobile-no-overflow'], samples: history.samples.length }));
await browser.close();
